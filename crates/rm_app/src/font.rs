//! Крошечный пиксельный шрифт 5×7 для интерфейса.
//!
//! Буквы нарисованы вручную прямо в коде: латиница, кириллица, цифры и
//! немного знаков. Каждая точка буквы рисуется как маленький прямоугольник
//! интерфейса, поэтому шрифту не нужны ни текстуры, ни файлы. Строчные
//! буквы показываются заглавными. Неизвестный символ рисуется как `?`.

/// Ширина и высота буквы в точках.
pub const GLYPH_W: usize = 5;
pub const GLYPH_H: usize = 7;

/// Возвращает 7 строк по 5 символов: `#` — точка есть.
pub fn glyph(c: char) -> &'static [&'static str; GLYPH_H] {
    let up = c.to_uppercase().next().unwrap_or(c);
    let up = if up == 'Ё' { 'Е' } else { up };
    GLYPHS
        .iter()
        .find(|(g, _)| *g == up)
        .map(|(_, rows)| rows)
        .unwrap_or(&QUESTION)
}

