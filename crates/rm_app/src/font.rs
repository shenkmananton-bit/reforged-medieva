/// Ширина строки в точках шрифта (с промежутком в одну точку между буквами).
pub fn text_width(text: &str) -> usize {
    let n = text.chars().count();
    if n == 0 { 0 } else { n * (GLYPH_W + 1) - 1 }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_are_well_formed() {
        for (c, rows) in GLYPHS {
            for r in rows {
                assert_eq!(r.chars().count(), GLYPH_W, "буква {c:?}");
            }
        }
    }

    #[test]
    fn russian_and_latin_are_covered() {
        for c in "абвгдеёжзийклмнопрстуфхцчшщъыьэюяabcdefghijklmnopqrstuvwxyz0123456789".chars()
        {
            assert!(*glyph(c) != QUESTION, "нет буквы {c:?}");
        }
    }
}
